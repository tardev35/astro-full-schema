#!/usr/bin/env node
//
// verify-build.mjs — read-only quality gate over dist/
//
// ── WHY THIS FILE EXISTS ────────────────────────────────────────────────────
// This repo is one template relaunched for unrelated brands every few hours,
// and the rebrand procedure lives in .claude/skills/rebrand-site/SKILL.md —
// 1,157 lines of prose. Every bug we have ever fixed there was fixed by adding
// another paragraph, which dilutes the paragraphs already present: a rule that
// is one of forty is a rule that gets skimmed.
//
// So new rules go HERE instead. A rule expressed as a function that exits
// non-zero cannot be skimmed, cannot be half-applied, and does not compete for
// attention with the rules around it. SKILL.md keeps one line telling the agent
// to run this; the rules themselves live in code.
//
// This file is also, deliberately, one a rebrand never rewrites — same reason
// the CSS in src/styles/global.css is where it is.
//
// ── ERRORS VS WARNINGS ──────────────────────────────────────────────────────
// Every check below is one of two severities:
//
//   error   The codebase passes this TODAY. If a future rebrand breaks it, that
//           is a regression and the build is not done. Exits 1.
//   warn    The codebase VIOLATES this today, and a scheduled phase of the
//           improvement plan is what fixes it. Printed with the phase that owns
//           it, but does not fail the build — a gate that is red on a clean
//           checkout teaches everyone to ignore it.
//
// When a phase lands, flip its checks from warn to error in one edit. That is
// the whole maintenance protocol; the `phase` tag on each warn says which ones.
//
// Usage:  node tools/verify-build.mjs        (after npm run build)

import fs from "node:fs";
import path from "node:path";

const DIST = "dist";

// Hosts allowed to appear in an attribute. Everything else is either a leak of
// a previous brand's domain or an unvetted third party.
//   yoalink.com          the affiliate redirect behind /login and /register —
//                        intentional, do not "fix" it
//   tinyurl.com          the /line short link, set in astro.config.mjs
//   schema.org           JSON-LD @context
//   fonts.googleapis.com the google-sans branch of BRAND_FONT
//   fonts.gstatic.com    ditto, the preconnect target
//   www.w3.org           SVG xmlns
const ALLOWED_HOSTS = new Set(["yoalink.com", "tinyurl.com", "schema.org", "fonts.googleapis.com", "fonts.gstatic.com", "www.w3.org"]);

// alt text that describes the file rather than the picture. A screen reader
// announcing "bank" or "Website Background" is worse than no image at all,
// because it spends the user's time to say nothing.
const USELESS_ALT = /^(bank|banks?\d*|logo|image|img|photo|picture|ภาพ|รูป|Website Background|slide\d*|banner\d*)$/i;

// "ภาพที่ 7" — a counter, not a description. Generated by the gallery loops.
const COUNTER_ALT = /(ภาพที่|image)\s*\d+\s*$/i;

const EMOJI = /\p{Extended_Pictographic}/u;

// Meta description window. Google truncates desktop snippets near 160
// characters; under ~150 leaves the SERP line half empty. Count CHARACTERS —
// Thai is 3 bytes per character in UTF-8, so any byte-based measurement reads
// roughly 3x too long and will send you rewriting descriptions that were fine.
const DESC_MIN = 150;
const DESC_MAX = 160;
const DESC_HARD_MAX = 200;

// Astro emits one <style> per page with inlineStylesheets:"always". Past this
// size the stylesheet is pushing the LCP image out of the parser's reach.
const INLINE_STYLE_MAX = 40_000;

const errors = [];
const warnings = [];

/** @param {string} where @param {string} msg */
const error = (where, msg) => errors.push({ where, msg });
/** @param {string} where @param {string} msg @param {string} phase */
const warn = (where, msg, phase) => warnings.push({ where, msg, phase });

// ── helpers ────────────────────────────────────────────────────────────────

function walkHtml(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walkHtml(p, out);
    else if (entry.name.endsWith(".html")) out.push(p.split(path.sep).join("/"));
  }
  return out;
}

const decodeEntities = (s) =>
  s
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#0?39;/g, "'")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&");

const attr = (tag, name) => {
  const m = tag.match(new RegExp(`\\s${name}="([^"]*)"`, "i"));
  return m ? m[1] : null;
};

const meta = (html, name) => {
  const m = html.match(new RegExp(`<meta[^>]+name="${name}"[^>]+content="([^"]*)"`, "i"));
  return m ? decodeEntities(m[1]) : null;
};

/** Character count, not code-unit count — an emoji is one character to a
 *  reader even when it is two UTF-16 units. */
const chars = (s) => [...s].length;

const VOID_TAGS = new Set(["area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"]);

/** Every .css Astro emitted, concatenated. Read once — `inlineStylesheets` is
 *  off, so a rule on html/body lives out here rather than in the page. */
let distCssCache = null;
const distCss = () => {
  if (distCssCache === null) {
    const dir = path.join(DIST, "_astro");
    distCssCache = !fs.existsSync(dir)
      ? ""
      : fs
          .readdirSync(dir)
          .filter((f) => f.endsWith(".css"))
          .map((f) => fs.readFileSync(path.join(dir, f), "utf8"))
          .join("\n");
  }
  return distCssCache;
};

/** Does the document set a text colour that everything else can inherit?
 *  Accepts an inline style on <html>/<body>, a <style> in the page, or a rule
 *  on html/body/:root in a stylesheet — any of the three is a real answer. */
const declaresColour = (css) => /(^|[,{}])\s*(?::root|html|body)[^{}]*\{[^{}]*(?:^|[;{\s])color\s*:/im.test(css);

function rootDeclaresColour(html) {
  for (const tag of [/<html\b[^>]*>/i, /<body\b[^>]*>/i]) {
    const m = html.match(tag);
    const style = m ? attr(m[0], "style") : null;
    if (style && /(^|;)\s*color\s*:/i.test(style)) return true;
  }
  for (const m of html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)) {
    if (declaresColour(m[1])) return true;
  }
  return declaresColour(distCss());
}

/**
 * Walk text nodes, tracking whether any ancestor carries aria-hidden="true".
 * A regex cannot answer that question — the attribute is on an ancestor, not on
 * the text — and pulling in a DOM parser for one check is not worth a
 * dependency in a repo that has none.
 *
 * Contents of <script> and <style> are skipped: they are not text a user or a
 * screen reader ever encounters.
 */
function eachTextNode(html, visit) {
  const stack = [];
  let hiddenDepth = 0;
  let i = 0;
  while (i < html.length) {
    const lt = html.indexOf("<", i);
    if (lt < 0) {
      if (hiddenDepth === 0) visit(html.slice(i), i);
      break;
    }
    if (lt > i && hiddenDepth === 0) visit(html.slice(i, lt), i);

    const gt = html.indexOf(">", lt);
    if (gt < 0) break;
    const raw = html.slice(lt, gt + 1);

    if (raw.startsWith("<!--")) {
      const end = html.indexOf("-->", lt);
      i = end < 0 ? html.length : end + 3;
      continue;
    }
    if (raw.startsWith("<!")) {
      i = gt + 1;
      continue;
    }

    const closing = raw[1] === "/";
    const name = (raw.match(/^<\/?\s*([a-zA-Z][a-zA-Z0-9-]*)/) || [])[1]?.toLowerCase();

    if (!name) {
      i = gt + 1;
      continue;
    }

    if (!closing && (name === "script" || name === "style")) {
      const close = html.toLowerCase().indexOf(`</${name}`, gt);
      i = close < 0 ? html.length : close;
      continue;
    }

    if (closing) {
      // Unwind to the matching open tag. Stray close tags are ignored rather
      // than treated as fatal — this is a linter, not a validator.
      for (let k = stack.length - 1; k >= 0; k--) {
        if (stack[k].name === name) {
          for (let j = stack.length - 1; j >= k; j--) {
            if (stack[j].hidden) hiddenDepth--;
          }
          stack.length = k;
          break;
        }
      }
    } else if (!VOID_TAGS.has(name) && !raw.endsWith("/>")) {
      const hidden = /\saria-hidden="true"/i.test(raw);
      if (hidden) hiddenDepth++;
      stack.push({ name, hidden });
    }
    i = gt + 1;
  }
}

// ── load the build ─────────────────────────────────────────────────────────

if (!fs.existsSync(DIST)) {
  console.error("verify-build: dist/ not found — run `npm run build` first.");
  process.exit(1);
}

const astroConfig = fs.readFileSync("astro.config.mjs", "utf8");
const siteRaw = (astroConfig.match(/site:\s*["']([^"']+)["']/) || [])[1];
if (!siteRaw) {
  console.error("verify-build: no `site:` in astro.config.mjs — canonical URLs cannot be checked.");
  process.exit(1);
}
const SITE = new URL(siteRaw);

const ADDRESS_TERMS = ["PostalAddress", "streetAddress", "addressLocality", "addressRegion", "addressCountry", "postalCode", '"address"'];

const BRAND_PROFILE = "src/lib/brandProfile.ts";
const addressLines = [];
let brandName = "";
if (fs.existsSync(BRAND_PROFILE)) {
  const profileSrc = fs.readFileSync(BRAND_PROFILE, "utf8");
  brandName = (profileSrc.match(/export const BRAND_NAME\s*(?::[^=]*)?=\s*["'`]([^"'`]+)/) || ["", ""])[1].trim();
  // Match the ASSIGNMENT, not "up to the first semicolon" — a semicolon inside
  // an inline type annotation truncated the old match and the check silently
  // read only `export const BRAND_ADDRESS: {`.
  const decl = profileSrc.match(/export const BRAND_ADDRESS\b[^=]*=([\s\S]*?)(?=\n\S|\n*$)/);
  if (decl && !/BRAND_NAME/.test(decl[0])) {
    error(
      BRAND_PROFILE,
      "BRAND_ADDRESS no longer keys off BRAND_NAME — that is what makes the address follow a rebrand on its own; pinned to anything else, a round that swaps the name ships the previous brand's address",
    );
  }
  const lines = profileSrc.match(/const ADDRESS_LINES[^=]*=\s*\[([\s\S]*?)\]/);
  if (lines) {
    for (const m of lines[1].matchAll(/"([^"\n]+)"/g)) {
      const line = m[1].trim();
      if (line.length > 6) addressLines.push(line);
    }
  }
}

const pages = walkHtml(DIST);

// A path -> exists lookup for internal links. Astro emits directory-style
// routes, so /promotion may be served from either promotion.html or
// promotion/index.html depending on build settings.
function resolvesInDist(pathname) {
  let p;
  try {
    p = decodeURIComponent(pathname);
  } catch {
    p = pathname;
  }
  p = p.replace(/^\/+/, "").replace(/\/+$/, "");
  if (p === "") return fs.existsSync(path.join(DIST, "index.html"));
  const candidates = [p, `${p}/index.html`, `${p}.html`];
  return candidates.some((c) => fs.existsSync(path.join(DIST, c)));
}

// ── checks ─────────────────────────────────────────────────────────────────

const inventory = [];

if (!fs.existsSync(path.join(DIST, "404.html"))) {
  // wrangler.toml declares not_found_handling = "404-page"; without this file
  // Cloudflare serves its own bare 404 for every mistyped URL.
  error("dist/", "no 404.html — src/pages/404.astro is missing or was renamed");
}

// Pages that ship on every brand, no exceptions.
//
// The rebrand procedure has a step for parking a sub-page the current brand did
// not ask for (it moves to src/pages-disabled/), and terms/privacy look exactly
// like candidates for it: sub-pages, present, not mentioned in the brief. They
// are not candidates. Every footer variant links to them, and a legal link that
// 404s is worse than one that was never there.
//
// They are also deliberately NOT registered in the uploader's PRESET_PAGES —
// that registry exists to toggle pages on and off, and these have no "off".
for (const route of ["terms", "privacy"]) {
  if (!fs.existsSync(path.join(DIST, route, "index.html"))) {
    error("dist/", `no /${route}/ — src/pages/${route}.astro was parked or deleted; it ships on every brand`);
  }
}

for (const file of pages) {
  const html = fs.readFileSync(file, "utf8");
  const where = file;

  // Astro writes a meta-refresh stub for every entry in `redirects:`
  // (astro.config.mjs sends /line to the LINE short link). That markup is
  // generated by the framework, not by anything in src/, so linting it only
  // produces findings nobody can act on.
  //
  // Test for the missing <html> element, not for the meta refresh: /login and
  // /register are hand-written pages that ALSO refresh (to the affiliate link,
  // which is intentional and must not be flagged), and skipping those would
  // quietly drop two real pages from every check below.
  if (/<meta[^>]+http-equiv="refresh"/i.test(html) && !/<html[\s>]/i.test(html)) continue;

  const robots = meta(html, "robots") || "";
  const indexable = !/noindex/i.test(robots);

  // --- structure that applies to every page, indexable or not ---

  if (!/<html[^>]+lang="th"/i.test(html)) {
    error(where, 'no lang="th" on <html>');
  }

  // A default text colour for the document. Nothing in global.css sets one —
  // it cannot, being the same file for a near-black brand and an ivory one —
  // so it arrives as an inline `color` on <html> from BRAND_TEXT.
  //
  // Without it every element that does not name its own colour falls through
  // to the browser default, which is black. On the near-black surface this
  // template has used for most brands that is not "dim", it is GONE: terms,
  // privacy and 404 are brand-neutral by design and name no colours at all,
  // so all three rendered as black-on-black until 2026-07-31.
  //
  // A rule in a real stylesheet counts too — the requirement is that the
  // document HAS a text colour, not that it arrives one particular way.
  if (!rootDeclaresColour(html)) {
    error(where, "no default text colour on <html>/<body> — text without its own colour class renders black (see BRAND_TEXT)");
  }

  // The address renders on /contact-us and in the footer, so it is on every
  // page by design. What still cannot happen is a PREVIOUS brand's address
  // surviving a rebrand — the derivation keys off BRAND_NAME precisely so that
  // cannot happen silently, and this is the check that proves it did not.
  for (const m of html.matchAll(/<address\b[^>]*>([\s\S]*?)<\/address>/gi)) {
    const text = decodeEntities(m[1].replace(/<[^>]*>/g, " "))
      .replace(/\s+/g, " ")
      .trim();
    if (brandName && !text.includes(brandName)) {
      error(where, `<address> does not name ${brandName} ("${text.slice(0, 60)}…") — a leftover address from an earlier brand (see BRAND_ADDRESS)`);
    }
    const mail = text.match(/[\w.+-]+@([\w.-]+)/);
    if (mail && mail[1].replace(/^www\./, "") !== SITE.hostname.replace(/^www\./, "")) {
      error(where, `contact email is at ${mail[1]}, not this brand's ${SITE.hostname} — an address block carried over from an earlier brand`);
    }
  }

  for (const m of html.matchAll(/<img\b[^>]*>/g)) {
    const tag = m[0];
    // Astro's <Image>/<Picture> serialise alt="" as a bare `alt`, which is
    // valid HTML and means exactly the same thing. An earlier version of this
    // check looked for `alt=` and so reported every correctly-marked
    // decorative image as having no alt at all.
    const hasAlt = /\salt(?=[\s>=])/i.test(tag);
    const alt = hasAlt ? (attr(tag, "alt") ?? "") : null;
    const src = attr(tag, "src") || "?";
    if (alt === null) {
      error(where, `<img> with no alt attribute: ${src.slice(0, 70)}`);
    } else if (alt !== "" && USELESS_ALT.test(alt.trim())) {
      error(where, `alt describes the file, not the picture: alt="${alt}"`);
    } else if (alt !== "" && COUNTER_ALT.test(alt.trim())) {
      error(where, `alt ends in a counter — describe the picture instead: "…${alt.trim().slice(-24)}"`);
    }
  }

  // Off-domain references in attributes. Scanning attributes only, not raw
  // text, keeps the Tailwind license banner inside <style> out of the results.
  for (const m of html.matchAll(/\s(?:href|src|action|content|srcset)="([^"]*)"/g)) {
    for (const u of m[1].split(/[\s,]+/)) {
      if (!/^https?:\/\//i.test(u)) continue;
      let host;
      try {
        host = new URL(u).host;
      } catch {
        continue;
      }
      if (host === SITE.host || ALLOWED_HOSTS.has(host)) continue;
      error(where, `off-domain reference to ${host} — previous brand's domain, or an unvetted third party`);
    }
  }

  // Internal links must land somewhere. A rebrand that points the layout at a
  // different Navbar* variant inherits that variant's hrefs, and several in the
  // inventory link to routes this template does not have (/signin, /gamedemo).
  for (const m of html.matchAll(/\shref="([^"]*)"/g)) {
    const href = m[1];
    if (href === "#") {
      error(where, 'href="#" — a link that goes nowhere');
      continue;
    }
    if (!href.startsWith("/") || href.startsWith("//")) continue;
    const pathname = href.split(/[?#]/)[0];
    if (/\.[a-z0-9]{2,5}$/i.test(pathname)) {
      // static asset
      let decoded;
      try {
        decoded = decodeURIComponent(pathname);
      } catch {
        decoded = pathname;
      }
      if (!fs.existsSync(path.join(DIST, decoded.replace(/^\/+/, "")))) {
        error(where, `href points at a file not in dist/: ${pathname}`);
      }
      continue;
    }
    if (!resolvesInDist(pathname)) {
      error(where, `href points at a route that does not exist: ${pathname}`);
    }
  }

  // Astro's define:vars forces is:inline, which strips type/async/defer and
  // leaves a parser-blocking script in the middle of the document.
  //
  // Indexable pages only. /login and /register are noindex forwarding stubs
  // whose entire content is a spinner and a setTimeout redirect — they use
  // define:vars to receive the affiliate URL, that redirect is deliberate, and
  // blocking a parser that has nothing left to parse costs nothing.
  if (indexable) {
    for (const m of html.matchAll(/<script(\s[^>]*)?>/g)) {
      if (!m[1]) {
        error(where, "<script> with no attributes — parser-blocking (define:vars forces is:inline)");
      }
    }
  }

  const inlineStyle = (html.match(/<style[^>]*>[\s\S]*?<\/style>/g) || []).join("").length;
  if (inlineStyle > INLINE_STYLE_MAX) {
    error(
      where,
      `${inlineStyle.toLocaleString()} bytes of inline <style> (limit ${INLINE_STYLE_MAX.toLocaleString()}) — ` + `check build.inlineStylesheets in astro.config.mjs is not back to "always"`,
    );
  }

  for (const m of html.matchAll(/\son(click|load|error|mouse[a-z]+|key[a-z]+|focus|blur)="/gi)) {
    error(where, `inline on${m[1]}= handler`);
  }

  // Decorative emoji reach the accessibility tree as their CLDR name — a
  // heading rendered "🔥 โปรโมชั่น" is announced "fire โปรโมชั่น".
  let bareEmoji = 0;
  eachTextNode(html, (text) => {
    for (const ch of decodeEntities(text)) if (EMOJI.test(ch)) bareEmoji++;
  });
  if (bareEmoji > 0) {
    error(where, `${bareEmoji} emoji outside any aria-hidden="true" element`);
  }

  // --- indexable pages only ---

  if (!indexable) continue;

  const title = (html.match(/<title>([\s\S]*?)<\/title>/) || [])[1];
  if (!title || !title.trim()) error(where, "empty or missing <title>");

  const desc = meta(html, "description");
  if (!desc || !desc.trim()) {
    error(where, "empty or missing meta description");
  } else {
    const n = chars(desc);
    if (n > DESC_HARD_MAX) {
      error(where, `meta description ${n} characters — will be truncated in every SERP (max ${DESC_HARD_MAX})`);
    } else if (n < DESC_MIN || n > DESC_MAX) {
      error(where, `meta description ${n} characters, outside ${DESC_MIN}–${DESC_MAX} — count CHARACTERS, not bytes`);
    }
  }

  const canonical = (html.match(/<link[^>]+rel="canonical"[^>]+href="([^"]*)"/i) || [])[1];
  if (!canonical) {
    error(where, "indexable page with no <link rel=canonical>");
  } else {
    let cu;
    try {
      cu = new URL(canonical);
    } catch {
      cu = null;
    }
    if (!cu) error(where, `canonical is not an absolute URL: ${canonical}`);
    else if (cu.host !== SITE.host) {
      error(where, `canonical points at ${cu.host}, not ${SITE.host} — leftover from the previous brand`);
    }
  }

  const h1s = [...html.matchAll(/<h1\b[^>]*>([\s\S]*?)<\/h1>/g)];
  if (h1s.length !== 1) {
    error(where, `${h1s.length} <h1> on an indexable page (must be exactly 1)`);
  }

  // JSON-LD: parses, and every self-referential URL agrees with the canonical
  // character for character. The trailing slash and the percent-encoding of
  // Thai routes are both easy to get subtly wrong by hand, and a mismatch
  // makes Google treat the markup as describing a different page.
  const ldBlocks = [...html.matchAll(/<script[^>]*application\/ld\+json[^>]*>([\s\S]*?)<\/script>/g)];
  if (ldBlocks.length === 0) {
    error(where, "indexable page with no JSON-LD at all");
  }
  for (const block of ldBlocks) {
    for (const term of ADDRESS_TERMS) {
      if (block[1].includes(term)) {
        error(
          where,
          `\`${term}\` inside JSON-LD — the contact address is visible text only. The generated one names a locality nobody has verified, and an operator-supplied registered address repeated across every brand domain is a machine-readable join key (the same reason sameAs is banned)`,
        );
      }
    }
    for (const line of addressLines) {
      if (block[1].includes(line)) {
        error(
          where,
          `registered address inside JSON-LD ("${line.slice(0, 30)}…") — it is visible text only; one address published as structured data across every brand domain is a machine-readable join key, the same reason sameAs is banned`,
        );
      }
    }
    let data;
    try {
      data = JSON.parse(block[1]);
    } catch (e) {
      error(where, `JSON-LD does not parse: ${e.message}`);
      continue;
    }
    if (!canonical) continue;
    const selfish = new Set();
    const visit = (node) => {
      if (Array.isArray(node)) return node.forEach(visit);
      if (!node || typeof node !== "object") return;
      for (const [key, value] of Object.entries(node)) {
        if (typeof value === "string" && /^https?:\/\//.test(value)) {
          if (key !== "url" && key !== "@id") continue;
          let u;
          try {
            u = new URL(value);
          } catch {
            continue;
          }
          if (u.host !== SITE.host) continue;
          // Same page as the canonical once both are normalised? Then the raw
          // strings had better match too.
          const norm = (s) => {
            let d = s;
            try {
              d = decodeURIComponent(s);
            } catch {
              /* keep raw */
            }
            return d.replace(/\/+$/, "");
          };
          if (norm(u.href.split("#")[0]) === norm(canonical) && value.split("#")[0] !== canonical) {
            selfish.add(`${key}: ${value}`);
          }
        } else visit(value);
      }
    };
    visit(data);
    for (const s of selfish) {
      error(where, `JSON-LD self-URL disagrees with canonical — ${s} vs ${canonical}`);
    }
  }

  // Legal links must reach the legal pages. Sending "นโยบายความเป็นส่วนตัว" to
  // the homepage is the kind of thing a reviewer notices before a user does.
  for (const m of html.matchAll(/<a\b([^>]*)>([\s\S]*?)<\/a>/g)) {
    const text = decodeEntities(m[2].replace(/<[^>]*>/g, "")).trim();
    if (!/เงื่อนไข|นโยบาย|ความเป็นส่วนตัว/.test(text)) continue;
    const href = attr(`<a${m[1]}>`, "href");
    if (!href || href === "#" || href === "/" || href === "") {
      error(where, `legal link "${text}" points at ${href || "(nothing)"}`);
    }
  }

  inventory.push({
    file,
    bytes: html.length,
    h1: h1s.map((m) => decodeEntities(m[1].replace(/<[^>]*>/g, "")).trim()),
    h2: [...html.matchAll(/<h2\b[^>]*>([\s\S]*?)<\/h2>/g)].map((m) =>
      decodeEntities(m[1].replace(/<[^>]*>/g, ""))
        .replace(/\s+/g, " ")
        .trim(),
    ),
    h3: [...html.matchAll(/<h3\b[^>]*>([\s\S]*?)<\/h3>/g)].length,
  });
}

// ── icons that ship but nothing points at ──────────────────────────────────
//
// public/ is copied into the build wholesale, so an icon left behind by an
// older brand keeps deploying under a fixed, guessable path long after the
// layout stopped linking it. favicon-16x16.png and favicon-32x32.png did
// exactly that: byte-identical to the SUMOHENG build of 2026-07-23, still
// served from every brand launched since. Two costs, and the second is worse:
// visitors may see another brand's logo, and anyone fetching that one path
// across the portfolio gets the same bytes back — a cross-domain match sharper
// than anything on the page, which is the very thing brandProfile.ts exists to
// avoid. The uploader writes 96x96/180/192/512 and never these two, so no
// rebrand was ever going to notice.
//
// Scoped to sized variants on purpose. favicon.ico and apple-touch-icon.png
// are fetched by browsers at their well-known root paths with no link at all,
// so "unreferenced" is a normal state for them, not a defect.
const LINK_ONLY_ICON = /^(favicon-\d+x\d+|android-chrome-[\w-]+|mstile-[\w-]+|web-app-manifest-[\w-]+)\.(png|svg|ico|webp|jpe?g)$/i;

{
  const referenced = new Set();
  const note = (u) => referenced.add(u.split(/[?#]/)[0].replace(/^\//, ""));

  for (const file of pages) {
    const html = fs.readFileSync(file, "utf8");
    for (const m of html.matchAll(/\s(?:href|src)="([^"]*)"/g)) note(m[1]);
  }
  const manifest = path.join(DIST, "site.webmanifest");
  if (fs.existsSync(manifest)) {
    for (const m of fs.readFileSync(manifest, "utf8").matchAll(/"src"\s*:\s*"([^"]+)"/g)) note(m[1]);
  }

  for (const entry of fs.readdirSync(DIST, { withFileTypes: true })) {
    if (!entry.isFile() || !LINK_ONLY_ICON.test(entry.name)) continue;
    if (referenced.has(entry.name)) continue;
    error("dist/", `${entry.name} ships but no page and no manifest entry links it — a previous brand's icon left in public/`);
  }
}

// ── processed images that ship but nothing points at ───────────────────────
//
// Astro emits an asset for every image it IMPORTS, not for every image it
// renders — and an eager import.meta.glob imports the whole folder. MainLayout
// globbed `banner*` for years to pick one hero, so banner.png (2.2 MB),
// banner2 and banner3 rode into dist/_astro and up to Cloudflare on every
// deploy: 3.1 MB, roughly a third of the build, that no page has ever linked.
// Nobody downloaded it, which is exactly why nobody noticed.
//
// Judged per SOURCE IMAGE, not per emitted file. Astro emits the untouched
// original for every image it imports — `.src` might be read at runtime, so it
// has no choice — and its image service sometimes generates a width nothing
// ends up asking for. Neither is reachable from this codebase, and a check
// that fails on them would be red on a clean checkout, which is how a gate
// teaches everyone to ignore it.
//
// So the question is not "is this exact file linked" but "did ANY version of
// this picture reach a page". Zero means it was imported and never rendered,
// which is a real mistake with a real fix.
//
// Grouping is by the name before the first dot, which is coarse — two source
// images sharing a basename count as one. That direction is safe: it can only
// hide a finding, never invent one.
const IMAGE_EXT = /\.(png|jpe?g|webp|avif|gif|svg)$/i;
const imageKey = (filename) => filename.slice(0, filename.indexOf(".")).toLowerCase();

{
  const referenced = new Set();

  // srcset holds several URLs per attribute and JSON blobs (the bank list)
  // carry paths inside a text node, so scan whole files rather than parsing
  // attributes.
  const scan = (text) => {
    for (const m of text.matchAll(/\/_astro\/([A-Za-z0-9._-]+)/g)) {
      if (IMAGE_EXT.test(m[1])) referenced.add(imageKey(m[1]));
    }
  };
  for (const file of pages) scan(fs.readFileSync(file, "utf8"));
  scan(distCss());

  const astroDir = path.join(DIST, "_astro");
  if (fs.existsSync(astroDir)) {
    const orphans = new Map();
    for (const name of fs.readdirSync(astroDir)) {
      if (!IMAGE_EXT.test(name)) continue;
      const key = imageKey(name);
      if (referenced.has(key)) continue;
      const bytes = fs.statSync(path.join(astroDir, name)).size;
      orphans.set(key, (orphans.get(key) ?? 0) + bytes);
    }
    for (const [key, bytes] of orphans) {
      error("dist/_astro/", `${key}.* ships ${Math.round(bytes / 1024)} kB but no page or stylesheet renders any version of it — an image imported without being used`);
    }
  }
}

// ── build-time randomness ──────────────────────────────────────────────────
//
// brandProfile.ts states the invariant: the same domain must produce
// byte-identical output on every build. A Math.random() in a component's
// FRONTMATTER runs at build time, so every deploy rewrites the live site's
// markup for no reason — and nothing about the page looks wrong, so it survives
// indefinitely. That is exactly what happened when the winners feed was moved
// to server-rendered rows: it reused the client helper, and two consecutive
// builds differed.
//
// Frontmatter only. The same call inside a <script> runs in the browser, which
// is the whole point of the widgets that use it.
const RANDOM_CALLS = /\b(Math\.random\s*\(|Date\.now\s*\(|new Date\s*\(\s*\))/;

function scanAstroFrontmatter(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      scanAstroFrontmatter(p);
      continue;
    }
    if (!entry.name.endsWith(".astro")) continue;
    const src = fs.readFileSync(p, "utf8");
    if (!src.startsWith("---")) continue;
    const end = src.indexOf("\n---", 3);
    if (end < 0) continue;
    // Strip comments first, or a note explaining the rule trips the rule.
    const frontmatter = src
      .slice(0, end)
      .replace(/\/\*[\s\S]*?\*\//g, "")
      .replace(/\/\/[^\n]*/g, "");
    const hit = frontmatter.match(RANDOM_CALLS);
    if (hit) {
      error(
        p.split(path.sep).join("/"),
        `${hit[1]}) in frontmatter — runs at BUILD time, so every deploy churns the markup. ` + `Use brandPick()/brandFlag() from src/lib/brandProfile.ts to derive it from the domain instead.`,
      );
    }
  }
}

scanAstroFrontmatter(path.join("src", "components"));
scanAstroFrontmatter(path.join("src", "pages"));
scanAstroFrontmatter(path.join("src", "layouts"));

// ── wrangler name vs brand domain ──────────────────────────────────────────
//
// Deploying with the previous brand's worker name overwrites the previous
// brand's live site. There is no undo for that, and nothing else in the
// pipeline notices. Rather than maintain a list of names already used — which
// would be one more file to forget — derive the expected name from the domain
// the build is already pointed at.
if (fs.existsSync("wrangler.toml")) {
  const wrangler = fs.readFileSync("wrangler.toml", "utf8");
  const name = (wrangler.match(/^\s*name\s*=\s*"([^"]+)"/m) || [])[1];
  const slug = SITE.hostname.replace(/^www\./i, "").split(/[-.]/)[0];
  if (name && slug && name.toLowerCase() !== slug.toLowerCase()) {
    error("wrangler.toml", `name = "${name}" but the site is ${SITE.hostname} (expected "${slug}") — ` + `deploying now would overwrite the "${name}" brand's live worker`);
  }
}

